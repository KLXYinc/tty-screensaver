#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FontStyle {
    Standard,
    Slanted,
    Mini,
}
impl FontStyle {
    pub fn height(&self) -> usize {
        match self {
            FontStyle::Standard => 5,
            FontStyle::Slanted => 5,
            FontStyle::Mini => 3,
        }
    }
}
pub fn generate_ascii_art(text: &str, style: FontStyle) -> Vec<String> {
    let height = style.height();
    let mut art = vec![String::new(); height];
    for c in text.to_uppercase().chars() {
        let pattern: Vec<&str> = get_char_pattern(c, style);
        for i in 0..height {
            art[i].push_str(pattern[i]);
            match style {
                FontStyle::Mini => art[i].push(' '),
                _ => art[i].push_str(" "),
            }
        }
    }
    art
}
pub fn get_char_pattern(c: char, style: FontStyle) -> Vec<&'static str> {
    match style {
        FontStyle::Standard => get_standard_char(c),
        FontStyle::Slanted => get_slanted_char(c),
        FontStyle::Mini => get_mini_char(c),
    }
}

